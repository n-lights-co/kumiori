/**
 * hebrewMarks — ヘブライ文字の点 (母音記号・ダゲシュ・シン/スィンの点など) の並びを、書体に渡す順に並べ替える。
 *
 * Unicode の正準結合クラス (ccc) は、ヘブライ文字の点に 1 つずつ別の値 (10〜26) を与えていて、正準順 (NFC・NFD) では
 * 「シュヴァ (10)・母音 (11〜20)・ダゲシュ (21)・メテグ (22)・ラフェ (23)・シンの点 (24)・スィンの点 (25)」の順になる。
 * 書体は、子音にすぐ続くダゲシュ・シン/スィンの点を合成済みの字形 (ב + ダゲシュ、ש + シンの点) に置き換える規則 (GSUB の ccmp) を持つ
 * ことが多く、間に母音記号が挟まる正準順のままでは、その規則が当たらない (Tinos・Arimo: ダゲシュ・シンの点が合成されず、位置もずれる)。
 * そこで、点の並びを「シン/スィンの点・ダゲシュ・ラフェ・ホラム・母音・シュヴァ・ヒリク・クブツ・メテグ」の順にしてから書体に渡す。
 *
 * 根拠: この順は HarfBuzz のもの (hb-unicode.hh の「Hebrew」の節の HB_MODIFIED_COMBINING_CLASS_CCC10〜CCC26。正準結合クラス 10〜26 を
 * 並べ替え用の値に読み替えて、結合文字を安定に並べ替える)。HarfBuzz の注釈は、この順を「SBL Hebrew の利用の手引き
 * (SBL Hebrew User Manual) に書かれた順」としている。手引きそのものは、この作業の環境から取得できず、原文は確かめていない
 * (W3C・Unicode の仕様に、この順を定めた節は見つけていない)。並べ替えるのは、ccc が 0 でなく互いに違う結合文字どうしだけなので、
 * 並べ替えた並びは元の並びと正準等価で、正準等価な並びを同じ見た目にすること (Unicode の適合性 C6) には反しない。
 * HarfBuzz は、このほかに「パタフ/カマツ + シュヴァ/ヒリク + メテグ (か下に付く記号)」の後ろ 2 つを入れ替える (hb-ot-shaper-hebrew.cc の
 * reorder_marks_hebrew)。これは入れていない。
 * 並べ替えるのは書体に渡す文字列だけ (fontkitShaping.ts の layout の差し替え)。組版の字 (GlyphArea の text・PDF の文字の取り出し) は元のまま。
 * 点の位置を書体の位置合わせ (GPOS の mark。点ごとに基底の字へ付ける) で決める書体 (Noto Sans Hebrew・Noto Serif Hebrew) では、字形の順が
 * 変わるだけで、見た目は変わらない
 */

/** ヘブライ文字の点 → 並べ替え用の値 (HarfBuzz の HB_MODIFIED_COMBINING_CLASS_CCC10〜CCC26)。コメントは正準結合クラス */
const ORDER = new Map<number, number>([
  [0x05b0, 22], // 10 シュヴァ
  [0x05b1, 15], // 11 ハタフ・セゴル
  [0x05b2, 16], // 12 ハタフ・パタフ
  [0x05b3, 17], // 13 ハタフ・カマツ
  [0x05b4, 23], // 14 ヒリク
  [0x05b5, 18], // 15 ツェレ
  [0x05b6, 19], // 16 セゴル
  [0x05b7, 20], // 17 パタフ
  [0x05b8, 21], // 18 カマツ
  [0x05c7, 21], // 18 カマツ・カタン
  [0x05b9, 14], // 19 ホラム
  [0x05ba, 14], // 19 ホラム・ハセル (ヴァヴ用)
  [0x05bb, 24], // 20 クブツ
  [0x05bc, 12], // 21 ダゲシュ・マピク
  [0x05bd, 25], // 22 メテグ
  [0x05bf, 13], // 23 ラフェ
  [0x05c1, 10], // 24 シンの点
  [0x05c2, 11], // 25 スィンの点
  [0xfb1e, 26], // 26 ヴァリカ
]);
/** ヘブライ文字の点が 2 つ以上続く並び */
const POINT_RUN = /[ְ-ׇֽֿׁׂﬞ]{2,}/g;
/** 並べ替えが要りうる文字列: ダゲシュ・ラフェ・シン/スィンの点・ホラムなど、正準順より前へ出す点を含む */
const HAS_POINT = /[ְ-ׇֽֿׁׂﬞ]/;

/** 文字列の中の、ヘブライ文字の点の並びを、書体に渡す順にする。並べ替えの要らない文字列は、そのまま返す */
export function reorderHebrewMarks(text: string): string {
  if (!HAS_POINT.test(text)) return text;
  return text.replace(POINT_RUN, (run) => {
    const cs = [...run];
    // 安定な並べ替え (同じ値の点は、元の順のまま)
    const sorted = cs.map((c, k) => ({ c, k, o: ORDER.get(c.codePointAt(0)!)! })).sort((a, b) => a.o - b.o || a.k - b.k);
    return sorted.map((x) => x.c).join('');
  });
}
