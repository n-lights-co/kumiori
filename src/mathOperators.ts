/** Figure 26 の 4 ビットの符号 → 分類 */
const ENCODING: Record<number, string> = { 0x0: 'A', 0x4: 'B', 0x8: 'C', 0x1: 'D', 0x2: 'E', 0x5: 'F', 0x6: 'G', 0x9: 'H', 0xa: 'I', 0xd: 'J', 0xc: 'K' };

/** B.1 の「演算子の分類を決める算法」 */
export function operatorCategory(content: string, form: OpForm): string {
  if (content.length !== 1 && content.length !== 2) return 'Default';
  let cp = content.codePointAt(0)!;
  if (content.length === 1 && cp >= 0x320 && cp <= 0x3ff) return 'Default';
  if (content.length === 2) {
    if ((cp === 0x1eef0 || cp === 0x1eef1) && form === 'postfix') return 'I';
    const second = content.charCodeAt(1);
    if (second === 0x338 || second === 0x20d2) cp = content.charCodeAt(0);
    else {
      const k = OP_2_ASCII.indexOf(content);
      if (k < 0) return 'Default';
      cp = 0x320 + k;
    }
  }
  if (form === 'infix' && (cp === 0x7c || cp === 0x223c)) return 'ForceDefault';
  if (form === 'prefix' && has(OP_L, cp)) return 'L';
  if (form === 'infix' && has(OP_M, cp)) return 'M';
  let key: number;
  if (cp <= 0x3ff) key = cp;
  else if (cp >= 0x2000 && cp <= 0x2bff) key = cp - 0x1c00;
  else return 'Default';
  key += form === 'infix' ? 0 : form === 'prefix' ? 0x1000 : 0x2000;
  for (const [s, n] of OP_ENTRIES) {
    const k0 = s % 0x4000;
    if (key >= k0 && key <= k0 + n) return ENCODING[Math.floor(s / 0x1000)] ?? 'Default';
  }
  return 'Default';
}

/**
 * 演算子の性質 (3.2.4.2 Dictionary-based attributes)。form を属性で指定していなければ (explicit が false)、
 * 分類が Default のとき infix・postfix・prefix の順に引き直す
 */
export function operatorProps(content: string, form: OpForm, explicit: boolean): OpProps & { category: string } {
  let cat = operatorCategory(content, form);
  if (cat === 'Default' && !explicit) {
    for (const f of ['infix', 'postfix', 'prefix'] as const) {
      cat = operatorCategory(content, f);
      if (cat !== 'Default') break;
    }
  }
  return { ...CATEGORY[cat], category: cat };
}

/** 囲みの記号 (Operators_fence) か */
export const isFenceOperator = (content: string) => [...content].length === 1 && has(OP_FENCE, content.codePointAt(0)!);
/** 区切りの記号 (Operators_separator) か */
export const isSeparatorOperator = (content: string) => [...content].length === 1 && has(OP_SEPARATOR, content.codePointAt(0)!);
/** 伸びる向きが行の方向 (inline) か */
export const stretchesInline = (cp: number) => has(STRETCH_INLINE, cp);
