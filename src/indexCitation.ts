/**
 * indexCitation — 索引のページ番号の並び (XSL 1.1 §6.10 Formatting Objects for Indexing) を作る手順。
 *
 * 入力は、鍵の付いた所ごとの「置かれた最初と最後のページ」(文書の先頭からの通し番号)。出力は、並べる順の、1 ページの項目か範囲。
 * 字にする (ページ番号の書式・前後の字・区切り) のは、組版 (layoutEngine) の側。HTML など、ほかの入力からも同じ手順を使える
 * (読み込みの形によらない)。
 *
 *  - §6.10.6 fo:index-key-reference: 鍵の付いた所ごとに、その領域のあるページすべてを引く。範囲はページの並びに開き、
 *    同じページを引く項目は 1 つだけ残す (分類 index-class によらない)
 *  - §6.10.7 fo:index-page-citation-list の Step A: すべての鍵の項目をページの順に並べる。
 *    merge-pages-across-index-key-references が merge なら、同じページの項目は 1 つだけ残す (§7.24.6)
 *  - 同 Step B: merge-sequential-page-numbers が merge なら、続いた 3 つ以上の項目を範囲にまとめる
 */

/** 鍵の付いた所 1 つの、置かれたページ (文書の先頭を 0 とする通し番号) */
export interface IndexSource {
  /** 索引の分類 (index-class。§7.24.1) */
  cls: string;
  /** 領域のある最初と最後のページ */
  first: number;
  last: number;
  /** 明示の範囲 (fo:index-range-begin〜fo:index-range-end) */
  range: boolean;
  /** 文書の中の順 (小さいほど前) */
  order: number;
  /** 最初のページの項目の飛び先 (その所の id)、最後のページの項目の飛び先 (終わりの印の id) */
  id?: string;
  endId?: string;
}

/** 引いたページ 1 つ (§6.10.6 の cited page item: ページ・引いた fo:index-key-reference・分類) */
export interface CitedPageItem {
  page: number;
  cls: string;
  /** 引いた fo:index-key-reference の番号 (文書の中の順) */
  ref: number;
  order: number;
  /** 2: 範囲の始まり・終わりの所の項目、1: 範囲の途中のページの項目、0: 範囲でない所の項目 */
  rank: 0 | 1 | 2;
  /** リンクの飛び先の id (その所がこのページにあるとき)。無ければページそのもの */
  target?: string;
}

/** 並べる 1 つ: 1 ページの項目 (last が無い) か、範囲 (first〜last) */
export interface CitedPageRange {
  first: CitedPageItem;
  last?: CitedPageItem;
}

/**
 * 1 つの fo:index-key-reference が引くページ (§6.10.6)。sources は、その鍵の付いた所 (文書の中の順)。
 *
 * “For each formatting object containing a matching index-key, a cited page item is generated for each page whose descendants
 * include areas returned from that formatting object.” 範囲は “page ranges are expanded to a sequence of individual cited page
 * items and all but one cited page item that refer to the same page are removed”。残すのは、範囲の始まり・終わりを指す項目のうち
 * 文書の中で最初のもの。無ければ、ページの中で最初の所の項目 (仕様の例 §6.10.1.2 では、範囲の途中のページの項目 [J] が、
 * 同じページの fo:wrapper の項目 [Y] より残されているので、範囲の途中の項目も、範囲でない所の項目より先に残す)
 */
export function citedPageItems(sources: IndexSource[], ref: number): CitedPageItem[] {
  const byPage = new Map<number, CitedPageItem>();
  for (const s of sources) {
    for (let p = s.first; p <= s.last; p++) {
      const edge = p === s.first || p === s.last;
      const rank = s.range ? (edge ? 2 : 1) : 0;
      const cur = byPage.get(p);
      if (cur && (cur.rank > rank || (cur.rank === rank && cur.order <= s.order))) continue;
      const target = p === s.first ? s.id : p === s.last ? s.endId : undefined;
      byPage.set(p, { page: p, cls: s.cls, ref, order: s.order, rank, ...(target !== undefined ? { target } : {}) });
    }
  }
  return [...byPage.values()].sort((a, b) => a.page - b.page);
}

export interface CollateOptions {
  /** merge-sequential-page-numbers (§7.24.5)。既定 true (merge) */
  mergeSequential?: boolean;
  /** merge-ranges-across-index-key-references (§7.24.4)。既定 true (merge) */
  mergeRangesAcrossReferences?: boolean;
  /** merge-pages-across-index-key-references (§7.24.6)。既定 true (merge) */
  mergePagesAcrossReferences?: boolean;
}

/**
 * fo:index-page-citation-list の Step A・Step B (§6.10.7)。perRef は、子の fo:index-key-reference ごとの citedPageItems の結果。
 *
 * Step B の「続いている」の条件: “The cited page items refer to page-viewport-areas that are consecutive children of the root of
 * the area tree. They have the same index-class. Either the cited page items are generated by the same fo:index-key-reference or
 * the value of merge-ranges-across-index-key-references is "merge".”
 * 別の鍵が同じページを引いて残っている (merge-pages… が leave-separate) とき、範囲にまとめる側の鍵 (または分類) の項目だけで続きを見る。
 * 仕様の例 (§6.10.1.2.1) のとおり、まとめた範囲の中のページを引く同じ組の項目は範囲に吸い込まれ、別の組の項目は範囲の後ろに残る
 */
export function collateCitedPages(perRef: CitedPageItem[][], opts: CollateOptions = {}): CitedPageRange[] {
  // Step A: ページの順 (同じページは、文書の中で先の所・先の fo:index-key-reference の順)
  let all = perRef.flat().sort((a, b) => a.page - b.page || a.order - b.order || a.ref - b.ref);
  if (opts.mergePagesAcrossReferences !== false) {
    // “Only the first occurrence, in document order of the fo:index-key-reference formatting objects, of a reference to a given
    // page number generated by multiple fo:index-key-reference formatting objects is retained.” (§7.24.6)
    const keep = new Map<number, CitedPageItem>();
    for (const it of all) {
      const cur = keep.get(it.page);
      if (!cur || it.ref < cur.ref) keep.set(it.page, it);
    }
    all = all.filter((it) => keep.get(it.page) === it);
  }
  if (opts.mergeSequential === false) return all.map((first) => ({ first }));
  // Step B: 組 (分類。鍵をまたがないなら、分類と鍵) ごとに、続いたページの並びを探す
  const across = opts.mergeRangesAcrossReferences !== false;
  const groups = new Map<string, number[]>();
  all.forEach((it, k) => {
    const key = across ? it.cls : `${it.ref}\u0000${it.cls}`;
    const g = groups.get(key);
    if (g) g.push(k);
    else groups.set(key, [k]);
  });
  // まとめた範囲: 最初の項目の位置 → 最後の項目。範囲に吸い込まれた項目の位置
  const rangeEnd = new Map<number, CitedPageItem>();
  const absorbed = new Set<number>();
  for (const idx of groups.values()) {
    let s = 0;
    while (s < idx.length) {
      let e = s;
      while (e + 1 < idx.length && all[idx[e + 1]].page - all[idx[e]].page <= 1) e++;
      // “merging sequences of three or more sequential cited page items into a cited page item range”
      if (all[idx[e]].page - all[idx[s]].page >= 2) {
        rangeEnd.set(idx[s], all[idx[e]]);
        for (let q = s + 1; q <= e; q++) absorbed.add(idx[q]);
      }
      s = e + 1;
    }
  }
  const out: CitedPageRange[] = [];
  all.forEach((it, k) => {
    if (absorbed.has(k)) return;
    const last = rangeEnd.get(k);
    out.push(last ? { first: it, last } : { first: it });
  });
  return out;
}
