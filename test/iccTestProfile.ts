/**
 * iccTestProfile — 試験に使う、小さな CMYK の出力機器の ICC プロファイルを、その場で作る。
 *
 * 印刷所の配るプロファイル (Japan Color など) は、使用許諾で配布や第三者の使用が限られるので、リポジトリにも試験にも使わない。
 * 代わりに、ICC.1:2010 (ISO 15076-1) の形どおりのプロファイルを、ここで組み立てる。色の変換の表は、本物の印刷条件を表すものではなく、
 * sRGB と ISO 32000-2 §10.4.2.4 の式 (c = 1 − R、k = min(c, m, y)。pdfRenderer.ts の rgbToCmyk) をおおまかに表にしたもの。
 *  - 頭 (128 バイト。§7.2): 大きさ・版 (2.4 か 4.3)・機器の種類 (既定 prtr。§7.2.5)・色空間 (既定 CMYK。§7.2.6)・PCS は Lab・'acsp'・PCS の光源 (D50)
 *  - タグの表 (§7.3): 数と、12 バイトずつの署名・位置・大きさ。中身は 4 バイトの境に置く。同じ型の表 (A2B0〜A2B2・B2A0〜B2A2) は同じ中身を指す
 *  - タグ (§8.2・§8.5 の出力のプロファイルに要るもの): desc (説明。版 2 は textDescriptionType、版 4 は multiLocalizedUnicodeType)・
 *    cprt (著作権の文)・wtpt (白色点)・A2B0・A2B1・A2B2 (CMYK → Lab。lut16Type)・B2A0・B2A1・B2A2 (Lab → CMYK。lut16Type)・gamt (色域の外か。lut16Type)
 * 説明と著作権の文は、Kumiori の試験で作ったものと分かる文にする。
 */

/** 作るプロファイルの説明 (desc) の既定の文 */
export const TEST_ICC_DESCRIPTION = 'Kumiori test CMYK profile (synthetic)';
/** 作るプロファイルの著作権 (cprt) の既定の文 */
export const TEST_ICC_COPYRIGHT = 'Generated by the Kumiori test suite; not a real printing condition. No copyright.';

export interface TestIccOptions {
  /** 機器の種類 (頭の 12〜15 バイト目。既定 'prtr') */
  deviceClass?: string;
  /** 色空間 (頭の 16〜19 バイト目。既定 'CMYK') */
  colorSpace?: string;
  /** 版 (既定 2 = 2.4.0。4 なら 4.3.0 で、desc を multiLocalizedUnicodeType で書く) */
  version?: 2 | 4;
  /** 説明 (desc) の文 */
  description?: string;
  /** 書かないタグの署名 */
  omit?: readonly string[];
}

const ascii = (s: string) => [...s].map((c) => c.charCodeAt(0));
const u32 = (v: number) => [(v >>> 24) & 255, (v >>> 16) & 255, (v >>> 8) & 255, v & 255];
const u16 = (v: number) => [(v >>> 8) & 255, v & 255];
const s15 = (v: number) => u32(Math.round(v * 65536) | 0);
const D50 = [0.9642, 1, 0.8249];
const clamp = (v: number) => Math.min(1, Math.max(0, v));

/** sRGB (0..1) → Lab (D50) */
function srgbToLab(r: number, g: number, b: number): [number, number, number] {
  const lin = (v: number) => (v <= 0.04045 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
  const [R, G, B] = [lin(r), lin(g), lin(b)];
  const xyz = [0.4360747 * R + 0.3850649 * G + 0.1430804 * B, 0.2225045 * R + 0.7168786 * G + 0.0606169 * B, 0.0139322 * R + 0.0971045 * G + 0.7141733 * B];
  const f = (t: number) => (t > (6 / 29) ** 3 ? Math.cbrt(t) : t / (3 * (6 / 29) ** 2) + 4 / 29);
  const [fx, fy, fz] = xyz.map((v, k) => f(v / D50[k]!));
  return [116 * fy! - 16, 500 * (fx! - fy!), 200 * (fy! - fz!)];
}

/** Lab (D50) → sRGB (0..1。色域の外は切る) */
function labToSrgb(L: number, a: number, b: number): [number, number, number] {
  const fy = (L + 16) / 116;
  const inv = (t: number) => (t > 6 / 29 ? t ** 3 : 3 * (6 / 29) ** 2 * (t - 4 / 29));
  const [X, Y, Z] = [inv(fy + a / 500) * D50[0]!, inv(fy) * D50[1]!, inv(fy - b / 200) * D50[2]!];
  // XYZ (D50) → 線形の sRGB (srgbToLab の行列の逆)
  const R = 3.1338561 * X - 1.6168667 * Y - 0.4906146 * Z;
  const G = -0.9787684 * X + 1.9161415 * Y + 0.033454 * Z;
  const B = 0.0719453 * X - 0.2289914 * Y + 1.4052427 * Z;
  const gam = (v: number) => clamp(v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055);
  return [gam(R), gam(G), gam(B)];
}

/** lut16Type ('mft2'。ICC.1:2010 §10.10): 入出力の曲線は線形 (2 点)、行列は単位行列、格子は grid 点 */
function lut16(nIn: number, nOut: number, grid: number, f: (x: number[]) => number[]): number[] {
  const lin = [...u16(0), ...u16(65535)];
  const out = [...ascii('mft2'), 0, 0, 0, 0, nIn, nOut, grid, 0, ...[1, 0, 0, 0, 1, 0, 0, 0, 1].flatMap(s15), ...u16(2), ...u16(2)];
  for (let k = 0; k < nIn; k++) out.push(...lin);
  const total = grid ** nIn;
  for (let i = 0; i < total; i++) {
    // 格子の並びは、初めの入力がいちばん遅く変わる (§10.10)
    const x: number[] = [];
    for (let k = nIn - 1, rest = i; k >= 0; k--, rest = Math.floor(rest / grid)) x[k] = (rest % grid) / (grid - 1);
    for (const v of f(x)) out.push(...u16(Math.round(clamp(v) * 65535)));
  }
  for (let k = 0; k < nOut; k++) out.push(...lin);
  return out;
}

/** 版 2 の lut16 の Lab の符号 (L は 0..100 → 0..0xFF00、a・b は −128..127.996 → 0..0xFFFF。ICC.1:2001-04 §6.5.7) を 0..1 にしたもの */
const encodeLab = ([L, a, b]: number[]) => [(L! / 100) * (0xff00 / 0xffff), ((a! + 128) * 256) / 0xffff, ((b! + 128) * 256) / 0xffff];
const decodeLab = ([l, a, b]: number[]) => [(l! * 0xffff * 100) / 0xff00, (a! * 0xffff) / 256 - 128, (b! * 0xffff) / 256 - 128];

/** 試験に使う CMYK の出力機器の ICC プロファイル (ファイルの冒頭の説明) */
export function testIccProfile(opts: TestIccOptions = {}): Uint8Array {
  const version = opts.version ?? 2;
  const description = opts.description ?? TEST_ICC_DESCRIPTION;
  const desc =
    version === 2
      ? // textDescriptionType (ICC.1:2001-04 §6.5.17): ASCII の文 (終わりの 0 を含む数)、Unicode と ScriptCode の文は空
        [...ascii('desc'), 0, 0, 0, 0, ...u32(description.length + 1), ...ascii(description), 0, ...u32(0), ...u32(0), ...u16(0), 0, ...new Array(67).fill(0)]
      : // multiLocalizedUnicodeType (ICC.1:2010 §10.13): en-US の 1 件 (UTF-16BE)
        [...ascii('mluc'), 0, 0, 0, 0, ...u32(1), ...u32(12), ...ascii('enUS'), ...u32(description.length * 2), ...u32(28), ...[...description].flatMap((c) => u16(c.charCodeAt(0)))];
  const cprt = version === 2 ? [...ascii('text'), 0, 0, 0, 0, ...ascii(TEST_ICC_COPYRIGHT), 0] : [...ascii('mluc'), 0, 0, 0, 0, ...u32(1), ...u32(12), ...ascii('enUS'), ...u32(TEST_ICC_COPYRIGHT.length * 2), ...u32(28), ...[...TEST_ICC_COPYRIGHT].flatMap((c) => u16(c.charCodeAt(0)))];
  const wtpt = [...ascii('XYZ '), 0, 0, 0, 0, ...D50.flatMap(s15)];
  // CMYK → Lab: R = (1 − C)(1 − K) などで sRGB にしてから Lab にする
  const a2b = lut16(4, 3, 3, ([c, m, y, k]) => encodeLab(srgbToLab((1 - c!) * (1 - k!), (1 - m!) * (1 - k!), (1 - y!) * (1 - k!))));
  // Lab → CMYK: sRGB にしてから ISO 32000-2 §10.4.2.4 の式
  const b2a = lut16(3, 4, 9, (lab) => {
    const [r, g, b] = labToSrgb(...(decodeLab(lab) as [number, number, number]));
    const [c, m, y] = [1 - r, 1 - g, 1 - b];
    const k = Math.min(c, m, y);
    return [c - k, m - k, y - k, k];
  });
  // 色域の外か (0 = 中): すべて中とする
  const gamt = lut16(3, 1, 2, () => [0]);
  const bodies: Array<[string, number[] | string]> = [
    ['desc', desc],
    ['cprt', cprt],
    ['wtpt', wtpt],
    ['A2B0', a2b],
    ['A2B1', 'A2B0'],
    ['A2B2', 'A2B0'],
    ['B2A0', b2a],
    ['B2A1', 'B2A0'],
    ['B2A2', 'B2A0'],
    ['gamt', gamt],
  ];
  const tags = bodies.filter(([sig]) => !opts.omit?.includes(sig));
  const tableEnd = 128 + 4 + 12 * tags.length;
  const table: number[] = [...u32(tags.length)];
  const data: number[] = [];
  const placed = new Map<string, [number, number]>();
  for (const [sig, body] of tags) {
    let at: [number, number] | undefined;
    if (typeof body === 'string') at = placed.get(body);
    if (!at) {
      const bytes = typeof body === 'string' ? (bodies.find(([s]) => s === body)![1] as number[]) : body;
      at = [tableEnd + data.length, bytes.length];
      data.push(...bytes, ...new Array((4 - (bytes.length % 4)) % 4).fill(0));
    }
    placed.set(sig, at);
    table.push(...ascii(sig), ...u32(at[0]), ...u32(at[1]));
  }
  const size = tableEnd + data.length;
  const head = new Array(128).fill(0);
  const put = (o: number, b: number[]) => b.forEach((x, k) => (head[o + k] = x));
  put(0, u32(size));
  put(8, version === 2 ? [0x02, 0x40, 0, 0] : [0x04, 0x30, 0, 0]);
  put(12, ascii((opts.deviceClass ?? 'prtr').padEnd(4)));
  put(16, ascii((opts.colorSpace ?? 'CMYK').padEnd(4)));
  put(20, ascii('Lab '));
  put(24, [...u16(2026), ...u16(1), ...u16(1), ...u16(0), ...u16(0), ...u16(0)]);
  put(36, ascii('acsp'));
  put(68, D50.flatMap(s15));
  return Uint8Array.from([...head, ...table, ...data]);
}
